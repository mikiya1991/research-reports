def tbl(headers, rows, note='', align=None):
    align = align or []
    th = ''.join(f"<th class='{'num' if (i < len(align) and align[i]=='n') else ''}'>{h}</th>"
                 for i, h in enumerate(headers))
    body = ''
    for r in rows:
        tds = ''
        for i, c in enumerate(r):
            cls = ''
            if i < len(align) and align[i] == 'n':
                cls = 'num'
            elif i < len(align) and align[i] == 'cls':
                cls = str(c)
            tds += f"<td class='{cls}'>{c if i < len(align) and align[i]=='cls' else c}</td>" if cls else f"<td>{c}</td>"
        body += f"<tr>{tds}</tr>"
    n = f"<p class='tbl-note'>{note}</p>" if note else ''
    return f"<div class='scroll'><table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>{n}"


