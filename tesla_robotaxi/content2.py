def fig_unit_waterfall(M):
    # base case per vehicle per year, USD thousands
    miles = 220 * 365 * 0.65 / 1000.0    # 65% utilization of "active days"
    rev = miles * 1000 * 1.70 / 1000.0   # $K
    cost_energy = miles * 1000 * 0.045 / 1000.0
    cost_maint = miles * 1000 * 0.08 / 1000.0
    cost_ins = miles * 1000 * 0.12 / 1000.0
    cost_tele = miles * 1000 * 0.05 / 1000.0
    dep = 30000 / 6 * 1.15 / 1000.0      # incl. financing/depot amortisation
    items = [
        ("每英里收入|$1.70", rev, 'start'),
        ("电费", -cost_energy, 'neg'),
        ("维保清洁", -cost_maint, 'neg'),
        ("保险", -cost_ins, 'neg'),
        ("远程协助", -cost_tele, 'neg'),
        ("车辆折旧|(含融资)", -dep, 'neg'),
        ("单车年毛现金贡献", rev - cost_energy - cost_maint - cost_ins - cost_tele - dep, 'total'),
    ]
    svg = C.waterfall(items, w=1120, h=430)
    return fig(5, "单车年化经济性（基准情景，单位：千美元）",
               "假设计算：年有效里程约 52,000 英里（日均 220 英里 × 65% 可用率）。"
               "该图为本报告推算，非任何公司披露。",
               svg,
               "本报告模型（输入参数见 5.1 表）· 证据等级 C（推算）")


def fig_sens(M):
    fleets = ["1,000", "5,000", "20,000", "100,000", "500,000"]
    percar = ["30", "60", "90", "120"]
    vals = []
    for pc in percar:
        row = []
        for f in fleets:
            n = float(f.replace(',', ''))
            row.append(n * float(pc) / 1000.0)   # $ billions
        vals.append(row)
    svg = C.sens(rows=[f"单车年贡献 {p} 千美元" for p in percar], cols=[f"车队 {f} 辆" for f in fleets],
                 vals=vals, w=1120, fmt=lambda v: f"${v:,.1f}B")
    return fig(6, "敏感度：车队规模 × 单车年贡献 → 年毛现金贡献（十亿美元）",
               "这是把 Robotaxi 从「叙事」翻译成「数字」的桥。要让这项业务贡献 100 亿美元年现金贡献，"
               "需要 10 万辆车 × 单车 10 万美元，或 50 万辆车 × 单车 2 万美元。",
               svg,
               "本报告模型 · 证据等级 C（推算）。颜色由红（低）到绿（高）")


